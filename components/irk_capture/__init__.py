def header_constant(header, name):
    """Read a numeric or string constant from one of the component's C++ headers.

    The firmware owns these values. Reading them keeps one definition instead of
    a Python copy that drifts from what the device actually enforces.
    """
    path = Path(__file__).parent / header
    try:
        text = path.read_text()
    except OSError as err:
        raise EsphomeError(f"irk_capture cannot read {path}: {err}") from err
    match = re.search(rf'\b{name}(?:\[\])? = (\d+|"[^"]*");', text)
    if match is None:
        raise EsphomeError(f"irk_capture: {name} is not defined in {path}")
    value = match.group(1)
    return value[1:-1] if value.startswith('"') else int(value)


# Custom-name length cap and the two built-in names (identity_name.h).
BLE_NAME_MAX_LEN = header_constant("identity_name.h", "BLE_NAME_MAX_LEN")
DEFAULT_BLE_NAME = header_constant("identity_name.h", "DEFAULT_BLE_NAME")
KEYBOARD_DEFAULT_NAME = header_constant("identity_name.h", "KEYBOARD_DEFAULT_NAME")

# The characters sanitize_ble_name() keeps at runtime (irk_capture_identity.cpp).
BLE_NAME_ALLOWED_CHARS = (
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 -_"
)


def validate_ble_name(value):
    """Reject a configured BLE name that would be stripped, trimmed, or truncated.

    The custom-name cap is BLE_NAME_MAX_LEN bytes for Samsung S24/S25
    compatibility. The runtime selects the advertising name, which can be
    the Keyboard default or a name generated by an identity refresh.
    """
    value = cv.string(value)
    if len(value.encode("utf-8")) > BLE_NAME_MAX_LEN:
        raise cv.Invalid(
            f"BLE name too long ({len(value.encode('utf-8'))} bytes). "
            f"Maximum {BLE_NAME_MAX_LEN} bytes for Samsung S24/S25 compatibility with "
            f"single-UUID advertising. Shorten your name."
        )
    unsupported = sorted(set(value) - set(BLE_NAME_ALLOWED_CHARS))
    if unsupported:
        raise cv.Invalid(
            "BLE name may contain only letters, digits, spaces, '-' and '_'. "
            f"Remove: {' '.join(repr(c) for c in unsupported)}"
        )
    if value != value.strip(" ") or not value:
        raise cv.Invalid("BLE name cannot be empty or start or end with a space.")
    return value


def validate_continuous_mode_config(config):
    """Validate continuous_mode and max_captures interaction"""
    continuous_mode = config.get(CONF_CONTINUOUS_MODE, True)
    max_captures = config.get(CONF_MAX_CAPTURES, 10)

    # Single-capture mode always stops after one publication, so values other
    # than 1 would misrepresent the runtime behavior (including 0="unlimited").
    if not continuous_mode and max_captures != 1:
        raise cv.Invalid(
            f"Configuration conflict: continuous_mode=false with max_captures={max_captures}. "
            f"To capture multiple unique devices, set continuous_mode=true. "
            f"For one device, set max_captures=1."
        )

    if continuous_mode and max_captures == 0:
        import logging

        logging.getLogger(__name__).warning(
            "max_captures=0 enables unlimited unique-device capture mode (no auto-stop). "
            "Only the 32 most recent devices are kept in the session history. "
            "This is not recommended for production. Set a specific limit (e.g., max_captures=5)."
        )

    return config


CONFIG_SCHEMA = cv.All(
    cv.Schema(
        {
            cv.GenerateID(): cv.declare_id(IRKCaptureComponent),
            cv.Optional(CONF_BLE_NAME, default=DEFAULT_BLE_NAME): validate_ble_name,
            cv.Optional(CONF_START_ON_BOOT, default=True): cv.boolean,
            cv.Optional(CONF_CONTINUOUS_MODE, default=True): cv.boolean,
            # 64 is far more than one session needs, and it bounds the memory
            # the capture history and the wizard's status response can use.
            cv.Optional(CONF_MAX_CAPTURES, default=10): cv.int_range(min=0, max=64),
            # Fires once per genuine capture or re-pair with irk, mac, and
            # verification; never for background reconnects.
            cv.Optional(CONF_ON_CAPTURE): automation.validate_automation(
                {cv.GenerateID(CONF_TRIGGER_ID): cv.declare_id(CaptureTrigger)}
            ),
        }
    ).extend(cv.COMPONENT_SCHEMA),
    validate_continuous_mode_config,
    cv.only_with_framework(["esp-idf"]),
)


async def to_code(config):
    var = cg.new_Pvariable(config[CONF_ID])
    await cg.register_component(var, config)
    cg.add(var.set_ble_name(config[CONF_BLE_NAME]))
    cg.add(var.set_start_on_boot(config[CONF_START_ON_BOOT]))
    cg.add(var.set_continuous_mode(config[CONF_CONTINUOUS_MODE]))
    cg.add(var.set_max_captures(config[CONF_MAX_CAPTURES]))
    for conf in config.get(CONF_ON_CAPTURE, []):
        trigger = cg.new_Pvariable(conf[CONF_TRIGGER_ID])
        cg.add(var.add_on_capture_trigger(trigger))
        # verification is "verified", "unverified" or "mismatch": whether the
        # IRK generated the address the device connected from.
        await automation.build_automation(
            trigger,
            [
                (cg.std_string, "irk"),
                (cg.std_string, "mac"),
                (cg.std_string, "verification"),
            ],
            conf,
        )

    # ESPHome 2026.9+ excludes built-in ESP-IDF components unless requested;
    # the sdkconfig options below enable NimBLE but do not pull "bt" back into
    # the build (leaving host/ble_gap.h missing).
    if hasattr(esp32, "request_bluetooth"):
        esp32.request_bluetooth()
    elif hasattr(esp32, "include_builtin_idf_component"):
        esp32.include_builtin_idf_component("bt")

    # NimBLE / Bluetooth sdkconfig — SINGLE SOURCE OF TRUTH.
    # These are applied after the esp32 platform processes the user's YAML
    # sdkconfig_options, so values set here win. Do NOT also declare them in
    # device/base YAML: a YAML value would be silently overridden by these.
    # The component only advertises and accepts connections, so only the
    # peripheral and broadcaster roles are compiled in. Leaving out central
    # and observer saves about 14 KB of flash (measured on an ESP32-C3 build).
    esp32.add_idf_sdkconfig_option("CONFIG_BT_ENABLED", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_BLUEDROID_ENABLED", False)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_ENABLED", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_ROLE_CENTRAL", False)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_ROLE_PERIPHERAL", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_ROLE_BROADCASTER", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_ROLE_OBSERVER", False)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_SECURITY_ENABLE", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_SM_LEGACY", True)
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_SM_SC", True)
    # Bonds live in RAM only. A captured IRK is published and the bond is then
    # disposable, so nothing about a peer should outlive a reboot. This is the
    # ESP-IDF default; setting it keeps that true if the default changes.
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_NVS_PERSIST", False)
    # The C++ state machine intentionally owns one connection handle and one
    # pairing session. Enforce that invariant in NimBLE as well.
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_MAX_CONNECTIONS", 1)

    # Above the 4096-byte default: ESP_LOG calls in GAP callbacks are
    # stack-heavy and need extra headroom under DEBUG logging.
    esp32.add_idf_sdkconfig_option("CONFIG_BT_NIMBLE_HOST_TASK_STACK_SIZE", 5120)
